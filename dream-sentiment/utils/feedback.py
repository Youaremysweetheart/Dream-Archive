def get_feedback(label: int, confidence: float, label_name: str = "其他") -> dict:
    is_strong = confidence >= 0.7
    intensity = "strong" if is_strong else "mild"

    resolved_name = label_name if label_name in FEEDBACK_POOL else "其他"
    pool = FEEDBACK_POOL[resolved_name][intensity]

    return {
        "label": label,
        "label_name": resolved_name,
        "confidence": round(confidence, 4),
        "intensity": intensity,
        "feedback": random.choice(pool),
    }
